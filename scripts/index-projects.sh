#!/usr/bin/env bash
# Regenerate the project index table in projects/README.md.
# Status is read from each projects/<name>/README.md.
# Usage: ./scripts/index-projects.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECTS="$ROOT/projects"
INDEX="$PROJECTS/README.md"

python3 - "$PROJECTS" "$INDEX" <<'PY'
import os
import re
import sys

projects_dir, index_path = sys.argv[1], sys.argv[2]
rows = []

for name in sorted(os.listdir(projects_dir)):
    path = os.path.join(projects_dir, name)
    readme = os.path.join(path, "README.md")
    if not os.path.isdir(path) or not os.path.isfile(readme):
        continue

    text = open(readme, encoding="utf-8").read()

    status = "idea"
    m = re.search(r"\|\s*\*\*Status\*\*\s*\|\s*`([^`]+)`", text)
    if m:
        status = m.group(1)

    touched = "—"
    m = re.search(r"\|\s*\*\*Last touched\*\*\s*\|\s*([0-9-]{10})", text)
    if m:
        touched = m.group(1)

    rows.append((name, status, touched))

if not rows:
    rows = [("_(none yet)_", "—", "—")]

table = ["| Project | Status | Last touched |", "| --- | --- | --- |"]
for name, status, touched in rows:
    cell = f"[{name}]({name}/README.md)" if name != "_(none yet)_" else name
    table.append(f"| {cell} | `{status}` | {touched} |")

block = "\n".join(table)

start = "<!-- INDEX:START -->"
end = "<!-- INDEX:END -->"

body = (
    "# projects/\n\n"
    "One folder = one project. No `.opencode/` inside.\n"
    "The table below is auto-generated by `scripts/index-projects.sh`.\n\n"
    f"{start}\n{block}\n{end}\n\n"
    "## Statuses Used\n\n"
    "| Status | Meaning |\n| --- | --- |\n"
    "| `idea` | new idea, no code yet |\n"
    "| `in-progress` | actively being worked on |\n"
    "| `review` | code done, under review |\n"
    "| `done` | shipped and approved |\n"
    "| `paused` | paused, not abandoned |\n\n"
    "## Create a New Project\n\n"
    "```bash\n./scripts/new-project.sh project-name\n```\n\n"
    "## Rules\n\n"
    "- Folder name: lowercase, hyphenated. Example: `toko-online`.\n"
    "- Each project has a `README.md`: purpose, status, how to run.\n"
    "- Update status in the project `README.md`, then run `./scripts/index-projects.sh`.\n"
    "- Diagrams and cross-project notes go in `docs/`, not here.\n\n"
    "## Record Results\n\n"
    "After a project ships:\n\n"
    "1. Mark it `done` or `paused` in the index.\n"
    "2. Save diagrams & decisions in `docs/`.\n"
    "3. Run `./scripts/index-projects.sh` to refresh the index.\n"
)

open(index_path, "w", encoding="utf-8").write(body)
print(f"{len(rows)} projects indexed")
PY
